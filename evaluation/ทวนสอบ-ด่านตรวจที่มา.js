/**
 * อ่าน CSV ที่มีเครื่องหมายคำพูดครอบและมีขึ้นบรรทัดใหม่อยู่ในเซลล์
 * เขียนเองเพราะไม่อยากเพิ่ม dependency ให้โครงงานเพียงเพื่อสคริปต์ตรวจสอบ
 */
function อ่านCSV(เนื้อไฟล์) {
  const s = เนื้อไฟล์.replace(/^﻿/, '');
  const แถว = [];
  let แถวนี้ = [];
  let เซลล์ = '';
  let ในคำพูด = false;
  for (let i = 0; i < s.length; i++) {
    const ch = s[i];
    if (ในคำพูด) {
      if (ch === '"') {
        if (s[i + 1] === '"') {
          เซลล์ += '"';
          i++;
        } else ในคำพูด = false;
      } else เซลล์ += ch;
    } else if (ch === '"') ในคำพูด = true;
    else if (ch === ',') {
      แถวนี้.push(เซลล์);
      เซลล์ = '';
    } else if (ch === '\n') {
      แถวนี้.push(เซลล์);
      แถว.push(แถวนี้);
      แถวนี้ = [];
      เซลล์ = '';
    } else if (ch !== '\r') เซลล์ += ch;
  }
  if (เซลล์ || แถวนี้.length) {
    แถวนี้.push(เซลล์);
    แถว.push(แถวนี้);
  }
  return แถว;
}

