const การเรียกทั้งหมด = [];
const แหล่งที่อ่านได้ = [];

for (const ชื่อไฟล์ of fs.readdirSync(ห้องผล)) {
  const เต็ม = path.join(ห้องผล, ชื่อไฟล์);

  // ข้ามไฟล์จากการรันแบบจำลองปลอม เพราะข้อมูลนำเข้าถูกตั้งไว้ตายตัวในโปรแกรม
  // ไม่ใช่สิ่งที่แบบจำลองจริงเลือกส่ง จึงใช้เป็นหลักฐานเรื่องพฤติกรรมไม่ได้
  // ถ้านับรวมจะทำให้จำนวนที่ด่านตัดดูเยอะเกินจริง
  if (ชื่อไฟล์.indexOf('accuracy-mock') === 0) continue;

  if (ชื่อไฟล์.endsWith('.csv')) {
    const แถว = อ่านCSV(fs.readFileSync(เต็ม, 'utf8'));
    if (แถว.length < 2) continue;
    const หัว = แถว[0];
    const iคำถาม = หัว.indexOf('คำถาม');
    const iข้อมูล = หัว.indexOf('ข้อมูลที่ส่งให้เครื่องมือ');
    const iเครื่องมือ = หัว.indexOf('เรียกเครื่องมือ');
    // ไฟล์รุ่นเก่ายังไม่มีคอลัมน์ข้อมูลนำเข้า ข้ามไปโดยไม่ถือเป็นข้อผิดพลาด
    if (iคำถาม < 0 || iข้อมูล < 0) continue;
    let นับ = 0;
    for (const r of แถว.slice(1)) {
      if (!r[iข้อมูล] || r[iข้อมูล] === '-') continue;
      if (iเครื่องมือ >= 0 && r[iเครื่องมือ].indexOf('personal_income_tax') < 0) continue;
      การเรียกทั้งหมด.push({ แหล่ง: ชื่อไฟล์, คำถาม: r[iคำถาม], ข้อมูล: r[iข้อมูล] });
      นับ++;
    }
    if (นับ) แหล่งที่อ่านได้.push(`${ชื่อไฟล์}  ${นับ} ครั้ง`);
    continue;
  }

  if (ชื่อไฟล์.startsWith('.checkpoint') && ชื่อไฟล์.endsWith('.json')) {
    let ก้อน;
    try {
      ก้อน = JSON.parse(fs.readFileSync(เต็ม, 'utf8'));
    } catch (e) {
      continue;
    }
    const รายการ = ก้อน.records ? Object.values(ก้อน.records) : [];
    let นับ = 0;
    for (const x of รายการ) {
      const ข้อมูล = x['ข้อมูลที่ส่งให้เครื่องมือ'];
      if (!ข้อมูล || ข้อมูล === '-') continue;
      if (String(x['เรียกเครื่องมือ'] || '').indexOf('personal_income_tax') < 0) continue;
      การเรียกทั้งหมด.push({ แหล่ง: ชื่อไฟล์, คำถาม: x['คำถาม'], ข้อมูล });
      นับ++;
    }
    if (นับ) แหล่งที่อ่านได้.push(`${ชื่อไฟล์}  ${นับ} ครั้ง`);
  }
}

