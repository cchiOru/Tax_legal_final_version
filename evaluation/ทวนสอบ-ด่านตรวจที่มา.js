for (const c of การเรียกทั้งหมด) {
  let p;
  try {
    p = JSON.parse(c.ข้อมูล);
  } catch (e) {
    แปลงJSONไม่ได้++;
    continue;
  }
  const q = String(c.คำถาม || '').toLowerCase();
  if (ตัวดักคำถามต่อเนื่อง.some((w) => q.indexOf(w) >= 0)) {
    ข้ามเพราะต่อเนื่อง++;
    continue;
  }
  const ผล = ตรวจที่มาของค่าลดหย่อน(p, c.คำถาม);
  if (ผล['ตัดออก'].length > 0) {
    ถูกตัด.push({ คำถาม: c.คำถาม, ข้อมูล: c.ข้อมูล, ตัดออก: ผล['ตัดออก'], แหล่ง: c.แหล่ง });
  }
}

