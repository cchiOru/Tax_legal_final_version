/** คำผิดแบบพิมพ์ตก: ลบตัวอักษรทีละตำแหน่ง */
function แบบพิมพ์ตก(คำ) {
  const ผล = new Set();
  for (let i = 0; i < คำ.length; i++) ผล.add(คำ.slice(0, i) + คำ.slice(i + 1));
  return [...ผล];
}

/** คำผิดแบบสลับตัวอักษรที่อยู่ติดกัน */
function แบบสลับตำแหน่ง(คำ) {
  const ผล = new Set();
  for (let i = 0; i < คำ.length - 1; i++) {
    ผล.add(คำ.slice(0, i) + คำ[i + 1] + คำ[i] + คำ.slice(i + 2));
  }
  return [...ผล];
}

/** คำผิดแบบสระผิด (พบบ่อย แต่วิธีนี้ไม่รองรับ) */
const คู่สระที่สับสนบ่อย = [
  ['ิ', 'ี'], ['ุ', 'ู'], ['ั', 'ะ'], ['เ', 'แ'], ['โ', 'เ'], ['ำ', 'ํา'],
];
function แบบสระผิด(คำ) {
  const ผล = new Set();
  for (const [a, b] of คู่สระที่สับสนบ่อย) {
    if (คำ.indexOf(a) >= 0) ผล.add(คำ.split(a).join(b));
    if (คำ.indexOf(b) >= 0) ผล.add(คำ.split(b).join(a));
  }
  ผล.delete(คำ);
  return [...ผล];
}

