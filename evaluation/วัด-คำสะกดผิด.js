const ปรับรูป = (s) =>
  String(s || '')
    .toLowerCase()
    .split('')
    .map((c) => ตารางพ้องเสียง[c] || c)
    .join('');

/** หาคำค้นจากคำถาม โดยเลือกได้ว่าจะเปิดการปรับรูปหรือไม่ */
function หาคำค้น(คำถาม, เปิดการปรับรูป) {
  const q = String(คำถาม || '').toLowerCase();
  const qn = ปรับรูป(q);
  const ผล = [];
  for (const [ตัวดัก, คำ] of ตารางคำสำคัญ) {
    let เจอ = q.indexOf(ตัวดัก) >= 0;
    if (!เจอ && เปิดการปรับรูป && ตัวดัก.length >= ความยาวต่ำสุดที่ปรับรูปได้) {
      เจอ = qn.indexOf(ปรับรูป(ตัวดัก)) >= 0;
    }
    if (เจอ && ผล.indexOf(คำ) < 0) ผล.push(คำ);
  }
  return ผล;
}

/** สร้างคำสะกดผิดโดยแทนพยัญชนะทีละตำแหน่งด้วยตัวอื่นในกลุ่มเสียงเดียวกัน */
function สร้างคำสะกดผิด(คำ) {
  const ผล = new Set();
  for (let i = 0; i < คำ.length; i++) {
    const ตัวเดิม = คำ[i];
    const กลุ่ม = กลุ่มพยัญชนะพ้องเสียง.find((g) => g.indexOf(ตัวเดิม) >= 0);
    if (!กลุ่ม) continue;
    for (const แทน of กลุ่ม) {
      if (แทน === ตัวเดิม) continue;
      ผล.add(คำ.slice(0, i) + แทน + คำ.slice(i + 1));
    }
  }
  return [...ผล];
}

