//  ตรวจว่าโจทย์ของตัวเองผ่านด่านตรวจที่มาของค่าลดหย่อนได้
// ---------------------------------------------------------------------------
//  ด่านนี้ตัดค่าลดหย่อนที่ผู้ใช้ไม่ได้เอ่ยถึงออก เพื่อกันแบบจำลองเติมตัวเลขเอง
//  ถ้าโจทย์เขียนไม่ชัดจนด่านตัดของที่ตั้งใจให้มีจริงทิ้ง เฉลยจะเป็นไปไม่ได้ตั้งแต่ต้น
//  ระบบที่ตอบถูกจะสอบตกทุกครั้ง แล้วเราจะไล่หาสาเหตุผิดที่
//
//  จับตั้งแต่ตอนสร้างชุดคำถาม ดีกว่าไปเจอตอนวัดผลจริงซึ่งเสียโควตาไปแล้ว
for (const j of โจทย์คำนวณ) {
  const ผลตรวจ = ตรวจที่มาของค่าลดหย่อน(j['ค่าที่ส่ง'], j['ถาม']);
  if (ผลตรวจ['ตัดออก'].length > 0) {
    throw new Error(
      'โจทย์นี้เขียนค่าลดหย่อนที่ไม่ปรากฏในตัวคำถาม ด่านตรวจที่มาจะตัดทิ้ง\n' +
        `  โจทย์: ${j['ถาม']}\n` +
        `  ถูกตัด: ${ผลตรวจ['ตัดออก'].map((x) => x['ช่อง'] + ' = ' + x['ค่า']).join(', ')}\n` +
        '  แก้โดยเขียนชื่อรายการนั้นลงในคำถามให้ชัด หรือเอาค่านั้นออกจากเฉลย'
    );
  }
}

for (const j of โจทย์คำนวณ) {
  const ผล = calculateThaiPIT(j['ค่าที่ส่ง']);
  const s = ผล['สรุป'];
  // ถ้าถูกหักภาษีไว้เกิน คำตอบคือยอดที่ขอคืนได้ มิใช่ยอดที่ต้องชำระเพิ่ม
  //
  // ชื่อคีย์ต้องตรงกับที่เครื่องคำนวณส่งออกจริง ซึ่งคือ ขอคืนภาษีได้
  // ครั้งแรกเขียนผิดเป็น ขอคืนได้ ทำให้ได้ค่า NaN แล้วชุดคำถามจะเสียทั้งข้อ
  // จึงต้องมีการตรวจด้านล่างว่าคำตอบเป็นตัวเลขจริงก่อนนำไปใช้
  const ขอคืน = s['ขอคืนภาษีได้'] || 0;
  const คำตอบ = ขอคืน > 0 ? ขอคืน : s['ต้องชำระเพิ่ม'] ?? s['ภาษีที่ต้องชำระ'];
  if (typeof คำตอบ !== 'number' || Number.isNaN(คำตอบ)) {
    throw new Error(
      `คำนวณคำตอบของโจทย์ไม่ได้ ได้ค่า ${คำตอบ}\n` +
        `  โจทย์: ${j['ถาม']}\n` +
        `  คีย์ที่เครื่องคำนวณส่งออก: ${Object.keys(s).join(', ')}`
    );
  }
  ใหม่.push({
    id: ออกรหัส(),
    category: 'คำนวณภาษี',
    difficulty: j['ความยาก'],
    requiresTool: true,
    question: j['ถาม'],
    check: 'exactNumber',
    expected: คำตอบ,
    ฐานกฎหมาย: 'ประมวลรัษฎากร มาตรา 40, 42 ทวิ ถึง 46, 47, 48',
    แหล่งอ้างอิง: ['เครื่องคำนวณของระบบ'],
    วิธีตรวจสอบ:
      `เงินได้รวม ${s['เงินได้พึงประเมินรวม'].toLocaleString('en-US')} ` +
      `หักค่าใช้จ่าย ${s['หักค่าใช้จ่าย'].toLocaleString('en-US')} ` +
      `หักลดหย่อน ${s['หักค่าลดหย่อน'].toLocaleString('en-US')} ` +
      `เงินได้สุทธิ ${s['เงินได้สุทธิ'].toLocaleString('en-US')} ` +
      `ภาษี ${s['ภาษีที่ต้องชำระ'].toLocaleString('en-US')} บาท`,
    เหตุผลที่ยาก: j['เหตุผลที่ยาก'],
    ชุด: 'ยาก',
  });
}

