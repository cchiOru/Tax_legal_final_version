//    แต่ "1,500,000" ไม่ผ่าน เพราะ Number() อ่านลูกน้ำไม่ออกและจะกลายเป็น 0
//    ถ้าด่านตัดลูกน้ำออกก่อนตรวจ ด่านจะบอกว่าผ่านทั้งที่เครื่องคำนวณอ่านไม่ได้
//    ซึ่งคือการสร้างความผิดพลาดเงียบตัวใหม่ขึ้นมาแทนตัวเก่า
