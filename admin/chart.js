'use strict';
/**
 * กราฟ (SVG วาดฝั่งเซิร์ฟเวอร์ ไม่ใช้ไลบรารี) และหัวตารางเรียงได้ของหน้าหลังบ้าน
 * กรองและเรียงผ่าน query string ส่วนโต้ตอบของกราฟอยู่ใน layout.js
 */

const { esc, เลข, วาดกราฟเส้น } = require('./layout');

/**
 * หาค่าเส้นตารางที่เป็นเลขกลม แบ่งราวสี่ช่อง
 * @param {number} สูงสุด
 * @param {boolean} จำนวนเต็ม ข้อมูลเป็นจำนวนนับ ห้ามมีเส้นที่เป็นทศนิยม
 * @returns {number[]} เริ่มที่ 0 ตัวสุดท้ายคือเพดานของกราฟ
 */
function เส้นตารางกลม(สูงสุด, จำนวนเต็ม = true) {
  if (!(สูงสุด > 0)) return [0, 1];
  const ดิบ = สูงสุด / 4;
  const หลัก = Math.pow(10, Math.floor(Math.log10(ดิบ)));
  let ก้าว = หลัก * 10;
  for (const ตัวคูณ of [1, 2, 2.5, 5, 10]) {
    if (หลัก * ตัวคูณ >= ดิบ) {
      ก้าว = หลัก * ตัวคูณ;
      break;
    }
  }
  if (จำนวนเต็ม) ก้าว = Math.max(1, Math.ceil(ก้าว));
  const เพดาน = Math.ceil(สูงสุด / ก้าว - 1e-9) * ก้าว;
  const ผล = [];
  for (let v = 0; v <= เพดาน + 1e-9; v += ก้าว) ผล.push(Number(v.toFixed(6)));
  return ผล;
}

/** ปัดค่าสูงสุดขึ้นเป็นเลขกลม */
function เพดานกลม(สูงสุด) {
  const เส้น = เส้นตารางกลม(สูงสุด, false);
  return เส้น[เส้น.length - 1];
}

/**
 * กราฟเส้นตามเวลา (ชื่อเดิมยังเป็น แท่งแนวตั้ง เพราะถูกเรียกหลายที่)
 * ค่า null = ไม่มีข้อมูล กราฟจะเว้นช่อง ไม่ลากลงศูนย์ (เช่น เวลาตอบของวันที่ไม่มีคนถาม)
 *
 * @param {Array<{ป้าย:string, ค่า:number|null, ป้ายเต็ม?:string}>} ข้อมูล เรียงจากเก่าไปใหม่
 * @param {string} หน่วย        ต่อท้ายตัวเลขในป้ายค่า เช่น คำถาม
 * @param {string} คำอธิบายว่าง ข้อความที่แสดงเมื่อไม่มีข้อมูล
 * @param {{ทศนิยม?:number}} ตัวเลือก
 */
function แท่งแนวตั้ง(ข้อมูล, หน่วย = '', คำอธิบายว่าง = 'ยังไม่มีข้อมูลพอจะวาดกราฟ', ตัวเลือก = {}) {
  if (!ข้อมูล || ข้อมูล.length === 0) return `<div class="ว่าง">${esc(คำอธิบายว่าง)}</div>`;

  // ข้อมูลชุดนี้เบราว์เซอร์ใช้วาดซ้ำตามความกว้างจริง (ตัววาดอยู่ใน layout.js)
  const สเปก = {
    v: ข้อมูล.map((d) => (d.ค่า === null || d.ค่า === undefined || d.ค่า === '' ? null : Number(d.ค่า))),
    l: ข้อมูล.map((d) => String(d.ป้าย)),
    f: ข้อมูล.map((d) => String(d.ป้ายเต็ม || d.ป้าย)),
    u: หน่วย,
    d: ตัวเลือก.ทศนิยม || 0,
    a: ตัวเลือก.พื้นที่ !== false,
  };

  // วาดขนาดตั้งต้นไว้ก่อน เห็นกราฟได้แม้ไม่มีสคริปต์
  const กว้าง = 1000;
  const สูง = 300;
  const ผล = วาดกราฟเส้น(สเปก, กว้าง, สูง);

  return `<div class="กล่องกราฟ"><svg class="กราฟเส้น" viewBox="0 0 ${กว้าง} ${สูง}" tabindex="0"
    role="img" aria-label="${esc(ผล.สรุป)}" data-spec="${esc(JSON.stringify(สเปก))}">${ผล.ใน}</svg></div>`;
}

/**
 * กราฟแท่งแนวนอน สำหรับเปรียบเทียบหมวดหรือกลุ่ม
 * ความยาวแท่งเทียบกับแท่งที่ยาวที่สุด ไม่ใช่ร้อยเปอร์เซ็นต์
 * @param {Array<{ป้าย:string, ค่า:number, ท้าย?:string}>} ข้อมูล
 */
function แท่งแนวนอน(ข้อมูล, คำอธิบายว่าง = 'ยังไม่มีข้อมูล') {
  if (!ข้อมูล || ข้อมูล.length === 0) return `<div class="ว่าง">${esc(คำอธิบายว่าง)}</div>`;
  const สูงสุด = Math.max(...ข้อมูล.map((d) => Number(d.ค่า) || 0), 1);
  return `<div class="กราฟ">${ข้อมูล
    .map((d) => {
      const ค่า = Number(d.ค่า) || 0;
      const กว้าง = Math.max(ค่า > 0 ? 1.5 : 0, (ค่า / สูงสุด) * 100);
      const ท้าย = d.ท้าย !== undefined ? d.ท้าย : เลข(ค่า);
      return `<span class="ชื่อแกน" title="${esc(d.ป้าย)}">${esc(d.ป้าย)}</span>
        <span class="แท่ง" title="${esc(d.ป้าย)} ${esc(ท้าย)}"><i style="width:${กว้าง.toFixed(1)}%"></i></span>
        <span class="ค่าท้าย">${esc(ท้าย)}</span>`;
    })
    .join('')}</div>`;
}

/**
 * สร้างหัวตารางที่กดเรียงได้
 * คีย์ต้องอยู่ในรายการที่อนุญาตในโค้ด เพราะจะถูกต่อเข้า ORDER BY
 * @param {URL} url          ที่อยู่ปัจจุบัน (คงตัวกรองอื่นไว้)
 * @param {string} คีย์      ชื่อในลิงก์
 * @param {string} ชื่อ      ข้อความที่แสดง
 * @param {object} ตัวเลือก  { ชิดขวา, เรียงอยู่, ทิศ }
 */
function หัวเรียงได้(url, คีย์, ชื่อ, { ชิดขวา = false, เรียงอยู่, ทิศ } = {}) {
  const กำลังเรียง = เรียงอยู่ === คีย์;
  // กดคอลัมน์เดิมซ้ำ = สลับทิศ คอลัมน์ใหม่เริ่มจากมากไปน้อย
  const ทิศถัดไป = กำลังเรียง && ทิศ === 'มากไปน้อย' ? 'น้อยไปมาก' : 'มากไปน้อย';
  const ที่อยู่ = new URL(url.href);
  ที่อยู่.searchParams.set('เรียง', คีย์);
  ที่อยู่.searchParams.set('ทิศ', ทิศถัดไป);
  const ลูกศร = กำลังเรียง ? (ทิศ === 'มากไปน้อย' ? ' ▾' : ' ▴') : '';
  return `<th${ชิดขวา ? ' class="เลข"' : ''}>
    <a class="หัวเรียง${กำลังเรียง ? ' กำลังเรียง' : ''}"
       href="${esc(ที่อยู่.pathname + ที่อยู่.search)}">${esc(ชื่อ)}${ลูกศร}</a></th>`;
}

/**
 * แปลงค่าเรียงจาก query string เป็นชิ้นส่วน ORDER BY ที่ปลอดภัย
 * @param {URL} url
 * @param {Object<string,string>} ที่อนุญาต  คีย์ในลิงก์ ไปเป็นนิพจน์ SQL ที่เขียนไว้ในโค้ด
 * @param {string} ค่าตั้งต้น
 */
function ตัวเรียง(url, ที่อนุญาต, ค่าตั้งต้น) {
  const ขอ = url.searchParams.get('เรียง') || '';
  const คีย์ = Object.prototype.hasOwnProperty.call(ที่อนุญาต, ขอ) ? ขอ : ค่าตั้งต้น;
  const ทิศ = url.searchParams.get('ทิศ') === 'น้อยไปมาก' ? 'น้อยไปมาก' : 'มากไปน้อย';
  return {
    คีย์,
    ทิศ,
    // นิพจน์มาจากรายการที่อนุญาตเท่านั้น ไม่ได้มาจากผู้ใช้
    sql: `${ที่อนุญาต[คีย์]} ${ทิศ === 'มากไปน้อย' ? 'DESC' : 'ASC'} NULLS LAST`,
  };
}

module.exports = { แท่งแนวตั้ง, แท่งแนวนอน, หัวเรียงได้, ตัวเรียง, เส้นตารางกลม, เพดานกลม };
