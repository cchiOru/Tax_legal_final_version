    'มาจากปุ่มที่ผู้ใช้กดหลังได้รับคำตอบในไลน์ เก็บเฉพาะคะแนนกับหมวดคำถาม ไม่เก็บว่าใครกดและไม่เก็บว่าคำตอบนั้นคืออะไร',
