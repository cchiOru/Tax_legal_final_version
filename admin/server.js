// รหัสผ่านเดียวจาก .env (ผู้ดูแลคนเดียว) session เก็บในหน่วยความจำ รีสตาร์ตแล้วต้องล็อกอินใหม่
const เซสชัน = new Map();
const อายุเซสชัน = 8 * 60 * 60 * 1000; // 8 ชั่วโมง

function สร้างเซสชัน() {
  const id = crypto.randomBytes(32).toString('hex');
  เซสชัน.set(id, Date.now() + อายุเซสชัน);
  return id;
}

function เซสชันใช้ได้(id) {
  if (!id) return false;
  const หมดอายุ = เซสชัน.get(id);
  if (!หมดอายุ) return false;
  if (Date.now() > หมดอายุ) {
    เซสชัน.delete(id);
    return false;
  }
  return true;
}

/** เทียบรหัสผ่านแบบใช้เวลาคงที่ กันการเดารหัสจากเวลาตอบกลับ (ห้ามใช้ ===) */
function รหัสผ่านถูก(ที่กรอก) {
  const a = Buffer.from(String(ที่กรอก || ''));
  const b = Buffer.from(รหัสผ่าน);
  if (a.length !== b.length) {
    // ยังต้องเทียบอยู่ดีเพื่อให้ใช้เวลาใกล้เคียงกัน
    crypto.timingSafeEqual(b, b);
    return false;
  }
  return crypto.timingSafeEqual(a, b);
}

function อ่านคุกกี้(req, ชื่อ) {
  const ทั้งหมด = req.headers.cookie || '';
  for (const ชิ้น of ทั้งหมด.split(';')) {
    const [k, ...v] = ชิ้น.trim().split('=');
    if (k === ชื่อ) return decodeURIComponent(v.join('='));
  }
  return null;
}

