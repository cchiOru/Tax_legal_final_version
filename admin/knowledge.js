// ---- ตัวจัดการเส้นทาง ----
async function จัดการ({ req, res, url, path, ส่ง, พาไป, อ่านฟอร์ม }) {
  // รายการทั้งหมด
  if (path === '/knowledge' && req.method === 'GET') {
    return ส่ง(res, await หน้ารายการ(url));
  }

  // ฟอร์มเพิ่มใหม่
  if (path === '/knowledge/new' && req.method === 'GET') {
    // ตั้งต้นเป็นหมวดที่เพิ่มบ่อยที่สุด
    return ส่ง(
      res,
      ฟอร์ม({ ค่า: { tax_year: 2567, category: 'การหักลดหย่อน', needs_calculation: '1' } })
    );
  }

  // บันทึกรายการใหม่ หรือกดทดลองค้น
  if (path === '/knowledge/new' && req.method === 'POST') {
    const f = await อ่านฟอร์ม(req);
    const { ผิด, เตือน } = ตรวจฟอร์ม(f);

    if (f.action === 'test') {
      const ผลค้น = f['ทดลอง'] ? await ทดลองค้น(f['ทดลอง'], f) : null;
      return ส่ง(res, ฟอร์ม({ ค่า: f, เตือน, ผลค้น, คำถามทดลอง: f['ทดลอง'] }));
    }
    if (ผิด.length) return ส่ง(res, ฟอร์ม({ ค่า: f, ผิด, เตือน }));

    // บันทึกผ่านฟอร์ม = มีคนเลือกเองแล้ว จึงตั้ง calc_verified เป็นจริง
    const แถว = await query(
      `INSERT INTO tax_law_knowledge
         (category, title, content, source, tax_year, needs_calculation, calc_verified)
       VALUES ($1, $2, $3, $4, $5, $6, true) RETURNING id`,
      [
        f.category,
        f.title.trim(),
        f.content.trim(),
        f.source.trim(),
        Number(f.tax_year),
        เป็นจริง(f.needs_calculation),
      ]
    );
    return พาไป(res, `/knowledge/${แถว[0].id}?ok=เพิ่มรายการใหม่เรียบร้อยแล้ว`);
  }

  // ---- ยืนยันค่าต้องคำนวณต่อ จากป้ายในตาราง ----
  // แก้แค่ needs_calculation กับ calc_verified จึงไม่ต้องตรวจฟอร์ม
  const ยืนยัน = path.match(/^\/knowledge\/(\d+)\/calc$/);
  if (ยืนยัน && req.method === 'POST') {
    const id = Number(ยืนยัน[1]);
    const f = await อ่านฟอร์ม(req);

    if (f.action === 'unverify') {
      // ยกเลิกการยืนยันอย่างเดียว ไม่แตะค่าต้องคำนวณต่อ
      await query(`UPDATE tax_law_knowledge SET calc_verified = false WHERE id = $1`, [id]);
    } else if (f.action === 'flip') {
      // สลับค่าเป็นตรงข้าม แล้วถือว่าตรวจแล้ว
      await query(
        `UPDATE tax_law_knowledge
         SET needs_calculation = NOT needs_calculation, calc_verified = true
         WHERE id = $1`,
        [id]
      );
    } else {
      // เก็บค่าที่ระบบเดาไว้ตามเดิม เปลี่ยนแค่สถานะว่าตรวจแล้ว
      await query(`UPDATE tax_law_knowledge SET calc_verified = true WHERE id = $1`, [id]);
    }

    // กลับหน้าเดิมพร้อมตัวกรอง รับเฉพาะที่อยู่ขึ้นต้นด้วย /knowledge กันการพาไปเว็บอื่น
    const กลับไป = String(f['กลับไป'] || '');
    const ปลอดภัย = /^\/knowledge(\?|$)/.test(กลับไป) ? กลับไป : '/knowledge';
    return พาไป(res, ปลอดภัย);
  }

  // ฟอร์มแก้ไข
  const แก้ = path.match(/^\/knowledge\/(\d+)$/);
  if (แก้ && req.method === 'GET') {
    const แถว = await query(
      `SELECT id, category, title, content, source, tax_year,
              needs_calculation, calc_verified
       FROM tax_law_knowledge WHERE id = $1`,
      [Number(แก้[1])]
    );
    if (!แถว.length) return ส่ง(res, หน้า({ title: 'ไม่พบ', active: '', body: '<h1>ไม่พบรายการนี้</h1>' }), 404);
    return ส่ง(res, ฟอร์ม({ ค่า: แถว[0], สำเร็จ: url.searchParams.get('ok') }));
  }

  // บันทึกการแก้ไข ทดลองค้น หรือลบ
  if (แก้ && req.method === 'POST') {
    const id = Number(แก้[1]);
    const f = await อ่านฟอร์ม(req);
    f.id = id;

    if (f.action === 'delete') {
      await query(`DELETE FROM tax_law_knowledge WHERE id = $1`, [id]);
      return พาไป(res, '/knowledge');
    }
    if (f.action === 'test') {
      const ผลค้น = f['ทดลอง'] ? await ทดลองค้น(f['ทดลอง'], f) : null;
      const { เตือน } = ตรวจฟอร์ม(f);
      return ส่ง(res, ฟอร์ม({ ค่า: f, เตือน, ผลค้น, คำถามทดลอง: f['ทดลอง'] }));
    }

    const { ผิด, เตือน } = ตรวจฟอร์ม(f);
    if (ผิด.length) return ส่ง(res, ฟอร์ม({ ค่า: f, ผิด, เตือน }));

    await query(
      `UPDATE tax_law_knowledge
       SET category = $2, title = $3, content = $4, source = $5, tax_year = $6,
           needs_calculation = $7, calc_verified = true
       WHERE id = $1`,
      [
        id,
        f.category,
        f.title.trim(),
        f.content.trim(),
        f.source.trim(),
        Number(f.tax_year),
        เป็นจริง(f.needs_calculation),
      ]
    );
    return พาไป(res, `/knowledge/${id}?ok=บันทึกการแก้ไขเรียบร้อยแล้ว`);
  }

  return ส่ง(res, หน้า({ title: 'ไม่พบหน้า', active: '', body: '<h1>ไม่พบหน้านี้</h1>' }), 404);
}

