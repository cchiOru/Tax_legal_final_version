test('RT-14 คำสำคัญคู่ใดปรับรูปแล้วต้องไม่ชนกันจนได้คำค้นต่างกัน', () => {
  // ตัวดักสองตัวที่ปรับรูปแล้วเหมือนกันแต่ให้คำค้นต่างกัน จะดึงเอกสารผิดเรื่องโดยไม่มีใครรู้
  const ตาราง = {};
  const กลุ่ม = [
    ['ส', 'ศ', 'ษ', 'ซ'], ['พ', 'ภ', 'ผ'], ['ท', 'ธ', 'ฑ', 'ฒ', 'ถ', 'ฐ'],
    ['ค', 'ข', 'ฆ', 'ฃ', 'ฅ'], ['น', 'ณ'], ['ล', 'ฬ'], ['ด', 'ฎ'],
    ['ต', 'ฏ'], ['ย', 'ญ'], ['ช', 'ฌ', 'ฉ'], ['บ', 'ป'],
  ];
  for (const g of กลุ่ม) for (const c of g) ตาราง[c] = g[0];
  const ปรับรูป = (s) => (s || '').toLowerCase().split('').map((c) => ตาราง[c] || c).join('');

  const ตามรูป = {};
  for (const [ตัวดัก, คำค้น] of cfg.keywordMap) {
    if (ตัวดัก.length < ความยาวต่ำสุดที่ปรับรูปได้) continue;
    const r = ปรับรูป(ตัวดัก);
    (ตามรูป[r] = ตามรูป[r] || []).push([ตัวดัก, คำค้น]);
  }

  // นับเฉพาะตัวดักที่ "ต่างกัน" แต่ปรับรูปแล้วเหมือนกัน
  // ตัวดักเดียวกันที่ใส่สองครั้งพร้อมคำค้นต่างกัน (เช่น ล.ย.03) เป็นความตั้งใจ ไม่นับ
  const ชน = Object.entries(ตามรูป).filter(([, v]) => {
    const ตัวดักที่ต่างกัน = new Set(v.map((x) => x[0]));
    if (ตัวดักที่ต่างกัน.size < 2) return false;
    return new Set(v.map((x) => x[1])).size > 1;
  });
  assert.strictEqual(
    ชน.length,
    0,
    'พบคำสำคัญที่ปรับรูปแล้วชนกันแต่ให้คำค้นต่างกัน:\n' +
      ชน.map(([r, v]) => `  ${r} ← ${JSON.stringify(v)}`).join('\n')
  );
});


