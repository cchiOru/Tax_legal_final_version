test('RT-22 รายการอนุสัญญาต้องกันความเข้าใจผิดสามข้อหลัก', () => {
  const ทั้งหมด = kb
    .filter((r) => r.title.indexOf('ภาษีซ้อน') >= 0)
    .map((r) => r.content)
    .join('\n');
  assert.ok(ทั้งหมด.length > 0, 'ไม่พบรายการเรื่องอนุสัญญาภาษีซ้อนในฐานข้อมูล');
  // หนึ่ง อนุสัญญาไม่ได้แปลว่าไม่ต้องเสียภาษี และไม่ได้กำหนดอัตราเอง
  assert.ok(
    ทั้งหมด.indexOf('ไม่ได้กำหนดอัตราภาษีเอง') >= 0,
    'ต้องเขียนให้ชัดว่าอนุสัญญาไม่ได้กำหนดอัตราภาษีเอง'
  );
  // สอง ใช้ได้เฉพาะผู้มีถิ่นที่อยู่ เกณฑ์ฝั่งไทยคือเกิน 180 วัน
  assert.ok(ทั้งหมด.indexOf('180 วัน') >= 0, 'ต้องระบุเกณฑ์ 180 วันของผู้มีถิ่นที่อยู่');
  // สาม ครอบคลุมเฉพาะภาษีทางตรง ไม่รวมภาษีมูลค่าเพิ่ม
  assert.ok(
    /ไม่ครอบคลุม[\s\S]{0,80}ภาษีมูลค่าเพิ่ม/.test(ทั้งหมด),
    'ต้องระบุว่าอนุสัญญาไม่ครอบคลุมภาษีมูลค่าเพิ่มและภาษีธุรกิจเฉพาะ'
  );
});
