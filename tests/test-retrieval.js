// เผื่อไว้สำหรับสิ่งที่เกิดขึ้น "หลัง" ส่งข้อมูลนำเข้าไปแล้ว
// ตัวเลขมาจากการวัดจริงที่บันทึกไว้ใน Modelfile
const เผื่อผลเครื่องมือ = 926; // ผลจากเครื่องคำนวณที่ยาวที่สุด
const เผื่อคำตอบ = 467; // คำตอบที่ยาวที่สุด
const เผื่อเรียกสองรอบ = เผื่อผลเครื่องมือ; // บางคำถามเรียกเครื่องมือมากกว่าหนึ่งรอบ
const เผื่อรวม = เผื่อผลเครื่องมือ + เผื่อคำตอบ + เผื่อเรียกสองรอบ;

function ขนาดข้อมูลนำเข้าสูงสุด() {
  const toolChars = JSON.stringify(
    cfg.tools.map((t) => ({
      type: 'function',
      function: { name: t.name, description: t.description, parameters: t.schema },
    }))
  ).length;

  let สูงสุด = 0;
  let ข้อที่ใหญ่ที่สุด = null;
  for (const q of DATASET.questions) {
    const คำถาม = q.คำถาม || q.question;
    const บริบท = contextFor(คำถาม);
    const คำสั่งระบบ = cfg.systemMessage
      .replace(/\{\{\s*\$json\.retrievedContext\s*\}\}/g, บริบท)
      .replace(/\{\{[^}]*display_name[^}]*\}\}/g, 'ผู้ทดสอบระบบ')
      .replace(/\{\{[^}]*questionCategory[^}]*\}\}/g, q.หมวด || 'ทั่วไป');
    const n = คำสั่งระบบ.length + คำถาม.length + toolChars;
    if (n > สูงสุด) {
      สูงสุด = n;
      ข้อที่ใหญ่ที่สุด = q.รหัส || q.id;
    }
  }
  // อัตราส่วนเดียวกับที่ฮาร์เนสใช้ ภาษาไทยประมาณ 1 โทเคนต่อ 1.5 ตัวอักษร
  return { ตัวอักษร: สูงสุด, โทเคน: Math.round(สูงสุด / 1.5), ข้อ: ข้อที่ใหญ่ที่สุด };
}

