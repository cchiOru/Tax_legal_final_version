test('RT-10 การเพิ่มการรองรับคำสะกดผิด ต้องไม่เปลี่ยนผลของคำถามทดสอบเดิม', () => {
  // ข้อสำคัญที่สุดของกลุ่ม: การเทียบแบบปรับรูปต้องไม่เปลี่ยนคำค้นของคำถามเดิมเลย
  // ไม่งั้นจะดึงเอกสารไม่เกี่ยวข้องมาเบียดเอกสารที่มีคำตอบ
  const ตารางพ้องเสียง = {};
  const กลุ่ม = [
    ['ส', 'ศ', 'ษ', 'ซ'], ['พ', 'ภ', 'ผ'], ['ท', 'ธ', 'ฑ', 'ฒ', 'ถ', 'ฐ'],
    ['ค', 'ข', 'ฆ', 'ฃ', 'ฅ'], ['น', 'ณ'], ['ล', 'ฬ'], ['ด', 'ฎ'],
    ['ต', 'ฏ'], ['ย', 'ญ'], ['ช', 'ฌ', 'ฉ'], ['บ', 'ป'],
  ];
  for (const g of กลุ่ม) for (const c of g) ตารางพ้องเสียง[c] = g[0];
  const ปรับรูป = (s) =>
    (s || '').toLowerCase().split('').map((c) => ตารางพ้องเสียง[c] || c).join('');

  const หาคำ = (คำถาม, ใช้ปรับรูป) => {
    const l = คำถาม.toLowerCase();
    const n = ปรับรูป(คำถาม);
    const found = [];
    for (const [ตัวดัก, คำค้น] of cfg.keywordMap) {
      let เจอ = l.indexOf(ตัวดัก) >= 0;
      if (!เจอ && ใช้ปรับรูป && ตัวดัก.length >= ความยาวต่ำสุดที่ปรับรูปได้) {
        เจอ = n.indexOf(ปรับรูป(ตัวดัก)) >= 0;
      }
      if (เจอ && found.indexOf(คำค้น) < 0) found.push(คำค้น);
    }
    return found.sort().join(',');
  };

  const เปลี่ยน = [];
  for (const q of DATASET.questions) {
    const คำถาม = q.คำถาม || q.question;
    if (หาคำ(คำถาม, false) !== หาคำ(คำถาม, true)) เปลี่ยน.push(q.รหัส || q.id);
  }
  assert.strictEqual(
    เปลี่ยน.length,
    0,
    `การปรับรูปไปเปลี่ยนผลของคำถามเดิม ${เปลี่ยน.length} ข้อ: ${เปลี่ยน.join(', ')}\n` +
      '  แปลว่ากำลังจับคู่กว้างเกินไป ให้ตรวจเกณฑ์ความยาวและกลุ่มพยัญชนะ'
  );
});

