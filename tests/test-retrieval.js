  // วิธีตรวจคือเทียบผลการหาคำสำคัญแบบตรงตัวล้วน กับแบบที่มีการปรับรูปเสริม
  // ถ้าต่างกันแม้แต่ข้อเดียว แปลว่าการปรับรูปกำลังแทรกแซงคำถามปกติ
