/** เรียกเส้นทางยืนยัน แล้วคืนคำสั่งที่ยิงไปกับที่อยู่ที่ถูกพาไป */
async function กดยืนยัน(id, action, กลับไป) {
  คำสั่งที่ยิงไป.length = 0;
  let ไปที่ = null;
  const url = new URL(`/knowledge/${id}/calc`, 'http://localhost:8080');
  await ความรู้.จัดการ({
    req: { method: 'POST' },
    res: {},
    url,
    path: url.pathname,
    ส่ง: () => {},
    พาไป: (_res, ที่อยู่) => {
      ไปที่ = ที่อยู่;
    },
    อ่านฟอร์ม: async () => ({ action, 'กลับไป': กลับไป }),
  });
  return { ไปที่, คำสั่ง: คำสั่งที่ยิงไป.map((x) => x.sql).join('\n') };
}

