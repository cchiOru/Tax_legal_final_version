/** ข้อมูลตัวอย่างที่คืนกลับ เลือกตามรูปแบบของคำสั่งที่ขอมา */
function ผลปลอม(sql, ค่า = []) {
  // จำลองหมวดที่มีอยู่จริงแต่ยังไม่มีข้อมูลสักรายการ
  if (ค่า.includes('การหักค่าใช้จ่าย')) return [];
  if (/LEFT JOIN v_usage_/.test(sql)) {
    return [
      { วันที่: '2569-08-09', จำนวนผู้ใช้: 4, จำนวนคำถาม: 11, เวลาตอบเฉลี่ย_ms: 2100 },
      { วันที่: '2569-08-10', จำนวนผู้ใช้: 7, จำนวนคำถาม: 25, เวลาตอบเฉลี่ย_ms: 1800 },
    ];
  }
  if (/จำนวนวันที่มีข้อมูล/.test(sql)) {
    return [{ จำนวนวันที่มีข้อมูล: 2, คำถามทั้งหมด: 36, รายการความรู้: 105 }];
  }
  if (/FROM answer_feedback/.test(sql) && /GROUP BY/.test(sql)) {
    return [
      { หมวด: 'การหักลดหย่อน', ทั้งหมด: 10, พอใจ: 9 },
      { หมวด: 'การคำนวณภาษี', ทั้งหมด: 4, พอใจ: 1 },
    ];
  }
  if (/FROM answer_feedback/.test(sql)) return [{ ทั้งหมด: 14, พอใจ: 10 }];
  if (/count\(\*\)::int AS จำนวน/.test(sql)) {
    return [
      { หมวด: 'การหักลดหย่อน', จำนวน: 25 },
      { หมวด: 'การยื่นแบบและชำระภาษี', จำนวน: 19 },
    ];
  }
  if (/WHERE NOT calc_verified/.test(sql)) return [{ n: 12 }];
  if (/FROM tax_law_knowledge/.test(sql)) {
    return [
      {
        id: 7,
        category: 'การหักลดหย่อน',
        // มีอักขระพิเศษ เพื่อตรวจว่าแปลงอักขระก่อนแสดง (กันฝังสคริปต์)
        title: 'ทดสอบ <script>alert(1)</script> & "อ้าง"',
        source: 'ประมวลรัษฎากร ม.47',
        tax_year: 2567,
        needs_calculation: true,
        calc_verified: false,
        ความยาว: 1800,
      },
    ];
  }
  return [];
}

const dbปลอม = {
  async query(sql, ค่า = []) {
    คำสั่งที่ยิงไป.push({ sql, ค่า });
    return ผลปลอม(sql, ค่า);
  },
  async ตรวจว่าอ่านแชทไม่ได้จริง() {},
  async ปิดการเชื่อมต่อ() {},
};

// ต้องสวม db ปลอมก่อน require โมดูลด้านล่าง ไม่งั้นจะได้ db จริง
const ที่อยู่db = require.resolve(path.join(ADMIN, 'db.js'));
require.cache[ที่อยู่db] = new Module(ที่อยู่db, null);
require.cache[ที่อยู่db].filename = ที่อยู่db;
require.cache[ที่อยู่db].loaded = true;
require.cache[ที่อยู่db].exports = dbปลอม;

