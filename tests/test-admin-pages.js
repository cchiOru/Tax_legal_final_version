test('AP-01 ค่าเรียงที่ไม่อยู่ในรายการที่อนุญาต ต้องไม่หลุดเข้าไปในคำสั่ง SQL', async () => {
  คำสั่งที่ยิงไป.length = 0;
  const อันตราย = "id; DROP TABLE tax_law_knowledge; --";
  await เปิดหน้าฐานข้อมูล(`/knowledge?เรียง=${encodeURIComponent(อันตราย)}&ทิศ=มากไปน้อย`);

  assert.ok(คำสั่งที่ยิงไป.length > 0, 'ไม่มีคำสั่งถูกยิงเลย แปลว่าทดสอบไม่ได้ทดสอบอะไร');
  for (const { sql } of คำสั่งที่ยิงไป) {
    assert.ok(!/DROP TABLE/i.test(sql), `พบคำสั่งอันตรายหลุดเข้าไปใน SQL:\n${sql}`);
  }
  assert.ok(
    คำสั่งที่ยิงไป.some(({ sql }) => /ORDER BY id DESC/.test(sql)),
    'เมื่อค่าเรียงใช้ไม่ได้ ต้องกลับไปเรียงตามรหัสซึ่งเป็นค่าตั้งต้น'
  );
});

