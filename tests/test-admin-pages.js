// ---------------------------------------------------------------------------
//  การเรียงจุดบนกราฟเส้นตามเวลา
// ---------------------------------------------------------------------------
//  ที่มา ภาพหน้าจอหน้าภาพรวมวันที่ 1 ตุลาคม 2569 แกนนอนขึ้นเป็น
//  7 ส.ค. 10 ส.ค. 14 ก.ย. 22 ส.ค. 13 ก.ย. 11 ส.ค. 12 ส.ค.
//
//  สาเหตุคือเรียงด้วย String(ค่า) ทั้งที่ไดรเวอร์ pg คืนคอลัมน์วันที่เป็น Date
//  String(Date) ขึ้นต้นด้วยชื่อวันในสัปดาห์ การเรียงจึงกลายเป็น
//  Fri Mon Sat Sun Thu Tue Wed ตามตัวอักษร ไม่ใช่ตามเวลา
//
//  เป็นความผิดพลาดที่มองไม่เห็น เพราะกราฟยังวาดออกมาครบและสวยงามตามปกติ
//  ต้องอ่านวันที่บนแกนทีละตัวถึงจะจับได้
// ---------------------------------------------------------------------------
test('AP-13 กราฟต้องเรียงจุดตามเวลาจริง ไม่ใช่ตามข้อความของวันที่', () => {
  const { เป็นวันที่ } = require('../admin/layout');

  // ชุดเดียวกับที่พบในภาพหน้าจอ สลับลำดับมาให้แล้ว
  const แถว = [
    new Date('2026-08-07'), new Date('2026-08-10'), new Date('2026-09-14'),
    new Date('2026-08-22'), new Date('2026-09-13'), new Date('2026-08-11'),
    new Date('2026-08-12'),
  ].map((d) => ({ วันที่: d }));
  const ค่าแรก = (r) => r[Object.keys(r)[0]];

  // ตรรกะเดียวกับที่ใช้ในหน้าภาพรวมของ admin/server.js
  const เรียงแล้ว = แถว.slice().sort((a, b) => {
    const วa = เป็นวันที่(ค่าแรก(a));
    const วb = เป็นวันที่(ค่าแรก(b));
    if (วa && วb) return วa.getTime() - วb.getTime();
    return String(ค่าแรก(a)).localeCompare(String(ค่าแรก(b)));
  });

  const ได้ = เรียงแล้ว.map((r) => ค่าแรก(r).toISOString().slice(0, 10));
  assert.deepStrictEqual(ได้, [
    '2026-08-07', '2026-08-10', '2026-08-11', '2026-08-12',
    '2026-08-22', '2026-09-13', '2026-09-14',
  ]);

  // ยืนยันว่าวิธีเดิมให้ลำดับผิดจริง ถ้าวันหนึ่งใครเผลอเปลี่ยนกลับไปจะได้รู้
  const แบบเดิม = แถว
    .slice()
    .sort((a, b) => String(ค่าแรก(a)).localeCompare(String(ค่าแรก(b))))
    .map((r) => ค่าแรก(r).toISOString().slice(0, 10));
  assert.notDeepStrictEqual(แบบเดิม, ได้, 'การเรียงด้วย String() ต้องให้ผลต่างจากการเรียงตามเวลา');
});

// ---------------------------------------------------------------------------
//  คอลัมน์วันที่ในหน้ารายงานปัญหา
// ---------------------------------------------------------------------------
//  คอลัมน์ ครั้งล่าสุด มาจาก max(created_at) ซึ่งไดรเวอร์ pg คืนเป็นอ็อบเจกต์ Date
//  โค้ดเดิมใช้ String(ค่า).slice(0, 10) ซึ่งเขียนไว้โดยสมมติว่าเป็นข้อความแบบ ISO
//  แต่เมื่อค่าเป็น Date ผลที่ได้คือ Mon Sep 28 คือชื่อวันกับเดือน ไม่ใช่วันที่ และไม่มีปี
//
//  เป็นบั๊กชนิดเดียวกับการเรียงจุดบนกราฟ ต่างกันแค่ที่แสดงผลแทนที่จะเป็นการเรียง
//  ทั้งสองจุดมาจากการลืมว่าคอลัมน์เวลาจากฐานข้อมูลไม่ใช่ข้อความ
// ---------------------------------------------------------------------------
test('AP-29 หน้ารายงานปัญหาต้องจัดรูปแบบวันที่ด้วยตัวช่วย ไม่ใช่ตัด String เอาเอง', () => {
  const fs = require('fs');
  const path = require('path');
  const โค้ด = fs.readFileSync(path.join(__dirname, '..', 'admin', 'server.js'), 'utf8');

  assert.ok(
    โค้ด.indexOf("วันที่เต็ม(r['ครั้งล่าสุด'])") >= 0,
    'คอลัมน์ ครั้งล่าสุด ต้องผ่าน วันที่เต็ม()'
  );
  assert.ok(
    โค้ด.indexOf("String(r['ครั้งล่าสุด']).slice") < 0,
    'ห้ามตัดข้อความจาก String(Date) มาแสดงเป็นวันที่'
  );

  // เคยมีบั๊กรากเดียวกันที่คอลัมน์ last_seen_at ของหน้าความรู้ที่ยังขาด
  // หน้านั้นถูกถอดออกทั้งหน้าแล้ว จึงเหลือตรวจเฉพาะรูปแบบที่ห้ามใช้ทั้งไฟล์
  assert.ok(
    !/String\([^)]*\)\.slice\(0, 10\)/.test(โค้ด),
    'ห้ามตัดข้อความจาก String(Date) มาแสดงเป็นวันที่ ให้ใช้ วันที่เต็ม() แทน'
  );

  // ยืนยันว่าวิธีเดิมให้ผลผิดจริง ถ้าใครเผลอเปลี่ยนกลับจะได้เห็นเหตุผล
  const { วันที่เต็ม } = require('../admin/layout');
  const ค่า = new Date('2026-09-28T11:35:00Z');
  assert.strictEqual(String(ค่า).slice(0, 10), 'Mon Sep 28');
  assert.strictEqual(วันที่เต็ม(ค่า), '28 ก.ย. 2569');
});
