/** เรียกหน้ารายการฐานข้อมูลผ่านตัวจัดการเส้นทาง แล้วคืน HTML ที่ได้ */
async function เปิดหน้าฐานข้อมูล(ที่อยู่) {
  const url = new URL(ที่อยู่, 'http://localhost:8080');
  let html = '';
  await ความรู้.จัดการ({
    req: { method: 'GET' },
    res: {},
    url,
    path: url.pathname,
    ส่ง: (_res, ผล) => {
      html = ผล;
    },
    พาไป: () => {},
    อ่านฟอร์ม: async () => ({}),
  });
  return html;
}

