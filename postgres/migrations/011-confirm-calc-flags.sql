       count(*) FILTER (WHERE needs_calculation)      AS ต้องคำนวณต่อ,
       count(*) FILTER (WHERE NOT needs_calculation)  AS ตอบได้เลย,
       count(*) FILTER (WHERE NOT calc_verified)      AS ยังไม่ยืนยัน
FROM tax_law_knowledge;

