-- ===========================================================================
--  010  ปุ่มรายงานปัญหา และโหมดคุยกับแอดมิน
-- ---------------------------------------------------------------------------
--  รองรับปุ่มที่ 6 ของ Rich Menu ซึ่งทำสองอย่าง
--    1. ผู้ใช้รายงานว่าคำตอบไม่ตรงหรือระบบตอบไม่ได้
--    2. ผู้ใช้ขอคุยกับแอดมินโดยตรงในห้องแชทเดิม
--
--  หลักความเป็นส่วนตัวที่บังคับในไฟล์นี้
--  ---------------------------------------------------------------------------
--  ข้อความคำถามของผู้ใช้ถูกเก็บไว้เพื่อให้ระบบนำไปปรับปรุงความรู้ได้
--  แต่ผู้ดูแลระบบต้องมองไม่เห็นข้อความนั้น เห็นได้เพียงหมวด สาเหตุ และจำนวน
--
--  บังคับด้วยสิทธิ์ของฐานข้อมูล มิใช่ด้วยการเขียนโค้ดให้ไม่แสดง
--    ตาราง answer_reports        ไม่ให้สิทธิ์ tax_admin_readonly เลย
--    วิว   v_report_summary      ให้สิทธิ์อ่าน เพราะไม่มีข้อความของผู้ใช้อยู่ในนั้น
--
--  วิวใน PostgreSQL ตรวจสิทธิ์ด้วยเจ้าของวิว มิใช่ผู้เรียก บัญชีผู้ดูแลจึงอ่าน
--  ผลสรุปได้โดยที่ยังอ่านตารางต้นทางไม่ได้ เป็นรูปแบบเดียวกับ v_usage_daily
--  ที่ใช้อยู่แล้วใน migration 005
-- ===========================================================================

BEGIN;

-- ---------------------------------------------------------------------------
--  ตารางรายงานปัญหาจากผู้ใช้
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS answer_reports (
    id           SERIAL PRIMARY KEY,

    -- สาเหตุที่ผู้ใช้กดรายงาน มาจากปุ่มที่กด จึงเป็นค่าจำกัดชุด
    --   not_match   ตอบไม่ตรงคำถาม
    --   cannot      ระบบบอกว่าตอบไม่ได้
    --   wrong_info  ข้อมูลผิด
    reason       VARCHAR(20) NOT NULL
                 CHECK (reason IN ('not_match', 'cannot', 'wrong_info')),

    -- หมวดของคำถามที่ถูกรายงาน ใช้ดูว่าปัญหากระจุกอยู่หมวดไหน
    category     VARCHAR(100),

    -- ข้อความคำถามล่าสุดของผู้ใช้ เก็บไว้ให้ระบบนำไปปรับปรุงฐานความรู้
    -- ผู้ดูแลระบบอ่านคอลัมน์นี้ไม่ได้ ดูส่วนสิทธิ์ท้ายไฟล์
    question     TEXT,

    -- จำนวนรายการความรู้ที่ค้นเจอตอนตอบคำถามนั้น
    -- ใช้ตรวจสมมติฐานว่า ค้นไม่เจอ ทำให้ถูกรายงาน จริงหรือไม่
    knowledge_hits INTEGER,

    -- สถานะการแก้ไข ให้ผู้ดูแลกดปิดเรื่องได้จากหน้าหลังบ้าน
    --   open  ยังไม่ได้จัดการ / done จัดการแล้ว / wontfix ไม่แก้
    status       VARCHAR(16) NOT NULL DEFAULT 'open'
                 CHECK (status IN ('open', 'done', 'wontfix')),

    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    resolved_at  TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS idx_answer_reports_created
    ON answer_reports (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_answer_reports_status
    ON answer_reports (status);

COMMENT ON TABLE answer_reports IS
    'รายงานปัญหาจากผู้ใช้ผ่านปุ่มใน Rich Menu '
    'คอลัมน์ question เป็นข้อความของผู้ใช้ ห้ามให้บัญชีผู้ดูแลระบบอ่าน';
COMMENT ON COLUMN answer_reports.question IS
    'ข้อความของผู้ใช้ เก็บไว้ให้ระบบนำไปปรับปรุงความรู้เท่านั้น '
    'บัญชี tax_admin_readonly ไม่มีสิทธิ์อ่านตารางนี้';

-- ---------------------------------------------------------------------------
--  วิวสรุปสำหรับหน้าหลังบ้าน  ไม่มีข้อความของผู้ใช้อยู่ในนั้นเลย
-- ---------------------------------------------------------------------------
--  จงใจไม่ select คอลัมน์ question แม้แต่ทางอ้อม
--  และไม่ใส่ id รายแถว เพื่อไม่ให้ไล่กลับไปหาเหตุการณ์รายครั้งได้
--  ผู้ดูแลเห็นเพียงว่า หมวดไหน ด้วยสาเหตุใด กี่ครั้ง ช่วงเวลาใด
CREATE OR REPLACE VIEW v_report_summary AS
SELECT
    date_trunc('day', created_at)::date AS วันที่,
    coalesce(category, 'ไม่ระบุหมวด')   AS หมวด,
    reason                              AS สาเหตุ,
    status                              AS สถานะ,
    count(*)                            AS จำนวนครั้ง,
    round(avg(knowledge_hits)::numeric, 1) AS ค้นเจอเฉลี่ย,
    min(created_at)                     AS ครั้งแรก,
    max(created_at)                     AS ครั้งล่าสุด
FROM answer_reports
GROUP BY 1, 2, 3, 4;

COMMENT ON VIEW v_report_summary IS
    'สรุปรายงานปัญหาแบบไม่มีข้อความของผู้ใช้ ใช้แสดงในหน้าหลังบ้าน';

-- ---------------------------------------------------------------------------
--  โหมดคุยกับแอดมิน
-- ---------------------------------------------------------------------------
--  เมื่อผู้ใช้ขอคุยกับแอดมิน ระบบจะหยุดตอบอัตโนมัติชั่วคราว
--  แล้วให้แอดมินพิมพ์ตอบเองผ่าน LINE Official Account Manager ในห้องเดิม
--
--  ทำไมต้องหยุดบอท ถ้าไม่หยุด ผู้ใช้จะได้คำตอบสองชุดพร้อมกัน
--  คือของแอดมินกับของบอท ซึ่งอาจขัดแย้งกันเอง และผู้ใช้จะไม่รู้ว่าควรเชื่ออันไหน
--
--  ทำไมเป็นเวลาสิ้นสุด ไม่ใช่ค่าจริงเท็จ
--  ถ้าเป็นค่าจริงเท็จแล้วแอดมินลืมปิด ผู้ใช้คนนั้นจะใช้บอทไม่ได้อีกเลย
--  การตั้งเวลาหมดอายุทำให้ระบบกลับมาทำงานเองได้เสมอ แม้ไม่มีใครมาปิดให้
ALTER TABLE users
    ADD COLUMN IF NOT EXISTS human_support_until TIMESTAMPTZ;

COMMENT ON COLUMN users.human_support_until IS
    'ถึงเวลานี้ให้บอทหยุดตอบ เพราะผู้ใช้กำลังคุยกับแอดมินอยู่ '
    'เลยเวลานี้แล้วบอทกลับมาตอบเองอัตโนมัติ';

CREATE INDEX IF NOT EXISTS idx_users_human_support
    ON users (human_support_until)
    WHERE human_support_until IS NOT NULL;

-- ---------------------------------------------------------------------------
--  สิทธิ์  ส่วนที่สำคัญที่สุดของไฟล์นี้
-- ---------------------------------------------------------------------------
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'tax_admin_readonly') THEN
        -- ห้ามอ่านตารางต้นทางเด็ดขาด เพราะมีข้อความของผู้ใช้อยู่
        EXECUTE 'REVOKE ALL ON answer_reports FROM tax_admin_readonly';

        -- ให้อ่านได้เฉพาะผลสรุปที่ไม่มีข้อความของผู้ใช้
        EXECUTE 'GRANT SELECT ON v_report_summary TO tax_admin_readonly';
    END IF;
END
$$;

COMMIT;

