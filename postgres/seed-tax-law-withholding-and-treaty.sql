มารวมคำนวณภาษีในรัฐถิ่นที่อยู่อีก เท่ากับเงินได้ก้อนนั้นหลุดออกจากฐานภาษีไป

วิธีเครดิตภาษี
รัฐถิ่นที่อยู่ยังนำเงินได้ก้อนนั้นมารวมคำนวณภาษีตามปกติ
แต่ยอมให้นำภาษีที่เสียไว้ในต่างประเทศมาหักออกจากภาษีที่คำนวณได้
ผลคือถ้าอัตราภาษีต่างประเทศต่ำกว่าไทย ยังต้องจ่ายส่วนต่างให้ไทย
ถ้าอัตราต่างประเทศสูงกว่า ก็ไม่ต้องจ่ายเพิ่ม แต่โดยทั่วไปไม่ได้คืนส่วนที่เกิน

ความต่างที่ควรจำ
วิธียกเว้นตัดเงินได้ออกจากฐานภาษี ส่วนวิธีเครดิตตัดที่ตัวภาษี ไม่ใช่ที่ฐาน
สองวิธีนี้จึงให้ผลไม่เท่ากันเมื่ออัตราภาษีสองประเทศต่างกัน

บางกรณีอนุสัญญาเพิกถอนสิทธิของรัฐแหล่งเงินได้ไว้ชัดเจน
ซึ่งเป็นการขจัดภาษีซ้อนอีกรูปแบบหนึ่ง เช่น การขนส่งทางอากาศระหว่างประเทศ
หรือการประกอบธุรกิจโดยไม่ผ่านสถานประกอบการถาวรในอีกรัฐหนึ่ง

สำหรับผู้มีเงินได้จากต่างประเทศที่เป็นบุคคลธรรมดา
กรมสรรพากรมีเครื่องมือช่วยคำนวณเครดิตภาษีให้ใช้บนเว็บไซต์
และการจะใช้สิทธิได้ต้องมีหลักฐานว่าเสียภาษีไว้ในต่างประเทศจริง
รวมถึงต้องเข้าเงื่อนไขการเป็นผู้มีถิ่นที่อยู่ตามอนุสัญญาด้วย

